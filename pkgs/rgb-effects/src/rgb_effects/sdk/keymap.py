def led_index_by_code(led_names: Sequence[str]) -> Mapping[int, int]:
    return MappingProxyType(
        {
            AZERTY_LED_CODES[name]: index
            for index, name in enumerate(led_names)
            if name in AZERTY_LED_CODES
        }
    )
